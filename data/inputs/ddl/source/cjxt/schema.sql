-- 用电信息采集系统（cjxt）DDL 导出，方言：oracle
-- 表数量：5

CREATE TABLE CJXT.R_TMNL_RUN (
  TERMINAL_ID NUMBER(16),
  TMNL_ASSET_NO VARCHAR2(32),
  TMNL_TYPE_CODE VARCHAR2(4),
  TERMINAL_ADDR VARCHAR2(32),
  ORG_NO VARCHAR2(16),
  RUN_STATUS VARCHAR2(2),
  INST_DATE DATE,
  CONSTRAINT PK_R_TMNL_RUN PRIMARY KEY (TERMINAL_ID)
);
COMMENT ON TABLE CJXT.R_TMNL_RUN IS '终端运行档案';
COMMENT ON COLUMN CJXT.R_TMNL_RUN.TMNL_TYPE_CODE IS '终端类型 01集中器 02专变终端';

CREATE TABLE CJXT.E_DATA_MP (
  ID NUMBER(16),
  TERMINAL_ID NUMBER(16),
  MP_SN NUMBER(16),
  MP_ID NUMBER(16),
  CONS_NO VARCHAR2(16),
  METER_ASSET_NO VARCHAR2(32),
  T_FACTOR NUMBER(10,2),
  CONSTRAINT PK_E_DATA_MP PRIMARY KEY (ID)
);
COMMENT ON COLUMN CJXT.E_DATA_MP.TERMINAL_ID IS '所属终端标识';
COMMENT ON COLUMN CJXT.E_DATA_MP.MP_SN IS '测量点序号';

CREATE TABLE CJXT.E_MP_DAY_READ (
  ID NUMBER(16),
  DATA_DATE DATE,
  PAP_R NUMBER(14,2),
  PRP_R NUMBER(14,2),
  RAP_R NUMBER(14,2),
  COL_TIME DATE,
  CONSTRAINT PK_E_MP_DAY_READ PRIMARY KEY (ID, DATA_DATE)
);
COMMENT ON COLUMN CJXT.E_MP_DAY_READ.PAP_R IS '正向有功总示数';

CREATE TABLE CJXT.E_MP_DAY_ENERGY (
  ID NUMBER(16),
  DATA_DATE DATE,
  PAP_E NUMBER(14,2),
  PRP_E NUMBER(14,2),
  RAP_E NUMBER(14,2),
  CONSTRAINT PK_E_MP_DAY_ENERGY PRIMARY KEY (ID, DATA_DATE)
);
COMMENT ON COLUMN CJXT.E_MP_DAY_ENERGY.DATA_DATE IS '数据日期';

CREATE TABLE CJXT.E_MP_POWER_CURVE (
  ID NUMBER(16),
  DATA_TIME DATE,
  P NUMBER(12,4),
  Q NUMBER(12,4),
  CONSTRAINT PK_E_MP_POWER_CURVE PRIMARY KEY (ID, DATA_TIME)
);
COMMENT ON COLUMN CJXT.E_MP_POWER_CURVE.Q IS '无功功率（kvar）';
